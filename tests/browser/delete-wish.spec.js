const { test, expect } = require('./fixtures');
const { expectNightTheme } = require('./night-assertions');
const { readFileSync, writeFileSync, mkdirSync } = require('node:fs');
const { join, dirname } = require('node:path');

// @test WSH-002-AC1 WSH-002-AC2 WSH-002-AC4 WSH-002-AC5 WSH-002-AC6 WSH-002-AC7 CON-003-AC1 CON-003-AC5
test('wish deletion asks for confirmation, supports cancellation, and preserves other wishes', async ({ page, context, appDataDir }) => {
 await page.goto('/');
 await page.getByLabel('Household name').fill('Family');
 await page.getByLabel('Household timezone').fill('Europe/Zurich');
 await page.getByRole('button', { name: 'Create access links' }).click();
 const family = await page.getByLabel('Family link', { exact: true }).inputValue();
 await page.getByRole('button', { name: 'Finish setup' }).click();
 const parent = page.url();
 const year = Number((await page.getByText(/Parent access/).textContent()).match(/\d+/)[0]);
 await page.getByLabel('Person name', { exact: true }).fill('Anna');
 await page.getByRole('button', { name: 'Add person', exact: true }).click();
 const file = join(appDataDir, 'households', 'Family', String(year), 'christmas', 'Anna', 'wishlist.yaml');
 const original = 'wishes:\n  - title: Wooden train\n    claims: [{name: Auntie}, {name: Uncle}]\n  - title: Another train\n';
 writeFileSync(file, original);
 await page.getByRole('link', { name: 'Anna', exact: true }).click();
 const listURL = page.url();
 await page.getByRole('button', { name: 'Delete wish: Wooden train', exact: true }).click();
 await expect(page.getByRole('heading', { name: 'Delete wish?', exact: true })).toBeVisible();
 await expect(page.getByText('Wooden train', { exact: true })).toBeVisible();
 await expect(page.getByText(/all attached claims/)).toBeVisible();
 expect(readFileSync(file, 'utf8')).toBe(original);
 await page.setViewportSize({ width: 390, height: 844 });
 await expectNightTheme(page);
 await page.screenshot({ path: test.info().outputPath('delete-confirmation-mobile.png'), fullPage: true });
 await page.getByRole('link', { name: 'Cancel', exact: true }).click();
 await expect(page).toHaveURL(listURL);
 expect(readFileSync(file, 'utf8')).toBe(original);
 await page.getByRole('button', { name: 'Delete wish: Wooden train', exact: true }).click();
 const stale = await context.newPage(); await stale.goto(listURL);
 await stale.getByRole('button', { name: 'Delete wish: Wooden train', exact: true }).click();
 await page.getByRole('button', { name: 'Permanently delete wish', exact: true }).click();
 await expect(page).toHaveURL(listURL);
 await expect(page.getByRole('heading', { name: 'Wooden train', exact: true })).toHaveCount(0);
 await expect(page.getByRole('heading', { name: 'Another train', exact: true })).toBeVisible();
 const remaining = readFileSync(file, 'utf8');
 expect(remaining).not.toMatch(/Wooden train|Auntie|Uncle/);
 expect(remaining).toContain('Another train');
 await stale.getByRole('button', { name: 'Permanently delete wish', exact: true }).click();
 await expect(stale.getByRole('heading')).toContainText('This wish changed');
 expect(readFileSync(file, 'utf8')).toBe(remaining);
 const guest = await context.newPage(); await guest.goto(family);
 await guest.getByRole('link', { name: 'Anna', exact: true }).click();
 await expect(guest.getByRole('button', { name: /Delete wish/ })).toHaveCount(0);
 // Saved history exposes no deletion controls to parents either.
 const oldFile = join(appDataDir, 'households', 'Family', String(year - 1), 'christmas', 'Anna', 'wishlist.yaml');
 mkdirSync(dirname(oldFile), { recursive: true }); writeFileSync(oldFile, original);
 const historyURL = new URL(listURL); historyURL.searchParams.set('year', String(year - 1));
 await page.goto(historyURL.toString());
 await expect(page.getByText('Read-only history', { exact: true })).toBeVisible();
 await expect(page.getByRole('button', { name: /Delete wish/ })).toHaveCount(0);
 await page.goto(listURL);
 await page.getByRole('button', { name: 'Delete wish: Another train', exact: true }).click();
 await page.getByRole('button', { name: 'Permanently delete wish', exact: true }).click();
 await expect(page.getByText('No wishes yet.', { exact: true })).toBeVisible();
 expect(readFileSync(oldFile, 'utf8')).toBe(original);
 await guest.reload(); await expect(guest.getByText('No wishes yet.', { exact: true })).toBeVisible();
});
