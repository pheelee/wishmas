const { test, expect } = require('./fixtures');
const { expectNightTheme } = require('./night-assertions');

// @test WSH-001-AC1 WSH-001-AC3 WSH-001-AC4 WSH-001-AC5 WSH-001-AC6 WSH-001-AC8 WSH-001-AC10 WSH-001-AC11 WSH-002-AC2 CON-003-AC1 CON-003-AC5
test('parents create and edit wish details while families browse', async ({ page, context }) => {
 await page.goto('/');
 await page.getByLabel('Household name').fill('Family');
 await page.getByLabel('Household timezone').fill('Europe/Zurich');
 await page.getByRole('button', { name: 'Create access links' }).click();
 const family = await page.getByLabel('Family link', { exact: true }).inputValue();
 await page.getByRole('button', { name: 'Finish setup' }).click();
 await page.getByLabel('Person name', { exact: true }).fill('Anna');
 await page.getByRole('button', { name: 'Add person', exact: true }).click();
 await page.getByRole('link', { name: 'Anna', exact: true }).click();
 const add = page.getByRole('region', { name: 'Add wish', exact: true });
 await add.getByLabel('Title', { exact: true }).fill('  Wooden train  ');
 await add.getByRole('button', { name: 'Add wish', exact: true }).click();
 await expect(page.getByRole('heading', { name: 'Wooden train', exact: true })).toBeVisible();
 await page.getByText('Edit wish', { exact: true }).click();
 const edit = page.locator('details form');
 await edit.getByLabel('Title', { exact: true }).fill('Electric train');
 await edit.getByLabel('Shop links').fill('https://first.example/item\nhttps://second.example/gift');
 await edit.getByLabel('Reference price').fill('12,50');
 await edit.getByLabel('Note', { exact: true }).fill('For a snowy afternoon.');
 await edit.getByRole('button', { name: 'Save wish', exact: true }).click();
 await expect(page.getByRole('alert')).toContainText('decimal point');
 const corrected = page.locator('form').filter({ has: page.getByRole('button', { name: 'Save corrected wish' }) });
 await expect(corrected.getByLabel('Note', { exact: true })).toHaveValue('For a snowy afternoon.');
 await corrected.getByLabel('Reference price').fill('12.50');
 await corrected.getByRole('button', { name: 'Save corrected wish' }).click();
 await expect(page.getByText('Reference price: 12.50', { exact: true })).toBeVisible();
 await expect(page.getByRole('link', { name: 'first.example', exact: true })).toHaveAttribute('href', 'https://first.example/item');
 await page.setViewportSize({ width: 390, height: 844 });
 await page.getByText('Edit wish', { exact: true }).click();
 await expectNightTheme(page);
 await page.screenshot({ path: test.info().outputPath('wishes-mobile.png'), fullPage: true });
 const guest = await context.newPage(); await guest.goto(family);
 await guest.getByRole('link', { name: 'Anna', exact: true }).click();
 await expect(guest.getByRole('heading', { name: 'Electric train', exact: true })).toBeVisible();
 await expect(guest.getByText('Edit wish', { exact: true })).toHaveCount(0);
 await expect(guest.getByLabel('Title', { exact: true })).toHaveCount(0);
 await expect(guest.getByRole('region', { name: 'Christmas wishes' }).getByRole('link')).toHaveText(['first.example', 'second.example']);
 await expectNightTheme(guest);
});
